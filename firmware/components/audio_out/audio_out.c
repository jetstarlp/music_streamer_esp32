esp_err_t audio_out_init(const audio_out_config_t *config)
{
    ESP_RETURN_ON_FALSE(config != NULL, ESP_ERR_INVALID_ARG, TAG, "config is NULL");
    ESP_RETURN_ON_FALSE(!s_ao.initialised, ESP_ERR_INVALID_STATE, TAG, "already initialised");
    ESP_RETURN_ON_FALSE(config->sample_rate_hz >= 8000 && config->sample_rate_hz <= 192000,
                        ESP_ERR_INVALID_ARG, TAG, "sample rate");
    ESP_RETURN_ON_FALSE(config->ring_buffer_bytes >= 64 * 1024, ESP_ERR_INVALID_ARG, TAG,
                        "ring buffer too small");

    esp_err_t ret = ESP_OK;
    s_ao.cfg = *config;
    /* pcm_ring needs a power of two */
    size_t ring = 1;
    while (ring * 2 <= s_ao.cfg.ring_buffer_bytes) {
        ring *= 2;
    }
    s_ao.cfg.ring_buffer_bytes = ring;
    if (s_ao.cfg.prebuffer_bytes > ring / 2) {
        s_ao.cfg.prebuffer_bytes = ring / 2;
    }
    s_ao.cfg.prebuffer_bytes &= ~(size_t)(AUDIO_OUT_BYTES_PER_FRAME - 1);
    s_ao.period_us = (uint32_t)((uint64_t)I2S_DMA_FRAME_NUM * 1000000u / s_ao.cfg.sample_rate_hz);

    /* XSMT low = muted, before anything else happens on the I2S pins. */
    const gpio_config_t xsmt_cfg = {
        .pin_bit_mask = 1ULL << BOARD_DAC_XSMT_GPIO,
        .mode = GPIO_MODE_OUTPUT,
        .pull_up_en = GPIO_PULLUP_DISABLE,
        .pull_down_en = GPIO_PULLDOWN_DISABLE,
        .intr_type = GPIO_INTR_DISABLE,
    };
    gpio_set_level(BOARD_DAC_XSMT_GPIO, 0);
    ESP_RETURN_ON_ERROR(gpio_config(&xsmt_cfg), TAG, "XSMT gpio");
    xsmt_set(false);

    /* Ring buffers in PSRAM (fall back to internal RAM without PSRAM). */
    const uint32_t ext = MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT;
    s_ao.ring_storage = heap_caps_malloc_prefer(ring, 2, ext, MALLOC_CAP_DEFAULT);
    s_ao.tone_storage = heap_caps_malloc_prefer(TONE_RING_BYTES, 2, ext, MALLOC_CAP_DEFAULT);
    s_ao.tone_scratch = heap_caps_malloc_prefer(TONE_CHUNK_FRAMES * AUDIO_OUT_BYTES_PER_FRAME, 2, ext,
                                                MALLOC_CAP_DEFAULT);
    s_ao.space_sem = xSemaphoreCreateBinary();
    s_ao.state_lock = xSemaphoreCreateMutex();
    s_ao.send_lock = xSemaphoreCreateMutex();
    ESP_GOTO_ON_FALSE(s_ao.ring_storage && s_ao.tone_storage && s_ao.tone_scratch && s_ao.space_sem &&
                      s_ao.state_lock && s_ao.send_lock,
                      ESP_ERR_NO_MEM, fail, TAG, "out of memory");
    pcm_ring_init(&s_ao.ring, s_ao.ring_storage, ring);
    pcm_ring_init(&s_ao.tone_ring, s_ao.tone_storage, TONE_RING_BYTES);
    pcm_engine_init(&s_ao.eng, &s_ao.ring, &s_ao.tone_ring, (uint32_t)s_ao.cfg.prebuffer_bytes,
                    (uint32_t)((uint64_t)s_ao.cfg.sample_rate_hz * PREBUFFER_MAX_WAIT_MS / 1000));

    /* I2S: master, TX only. The DMA buffers start zeroed; from then on the
     * interrupt refills every buffer right after it was sent. No auto_clear:
     * it would wipe what on_sent just wrote. */
    i2s_chan_config_t chan_cfg = I2S_CHANNEL_DEFAULT_CONFIG(I2S_NUM_0, I2S_ROLE_MASTER);
    chan_cfg.dma_desc_num = I2S_DMA_DESC_NUM;
    chan_cfg.dma_frame_num = I2S_DMA_FRAME_NUM;
    chan_cfg.auto_clear = false;
    ESP_GOTO_ON_ERROR(i2s_new_channel(&chan_cfg, &s_ao.tx, NULL), fail, TAG, "i2s_new_channel");

    i2s_std_config_t std_cfg = {
        /* No APLL on the S3: the clock comes from PLL_F160M through a fractional
         * divider. MCLK is not routed to a pin; BCK = 32 x fs for 16-bit slots,
         * which the PCM5102A PLL accepts (16/24/32-bit, 32/48/64 x fs). */
        .clk_cfg = I2S_STD_CLK_DEFAULT_CONFIG(s_ao.cfg.sample_rate_hz),
        .slot_cfg = I2S_STD_PHILIPS_SLOT_DEFAULT_CONFIG(I2S_DATA_BIT_WIDTH_16BIT, I2S_SLOT_MODE_STEREO),
        .gpio_cfg = {
            .mclk = I2S_GPIO_UNUSED,
            .bclk = BOARD_I2S_BCK_GPIO,
            .ws   = BOARD_I2S_WS_GPIO,
            .dout = BOARD_I2S_DOUT_GPIO,
            .din  = I2S_GPIO_UNUSED,
            .invert_flags = { .mclk_inv = false, .bclk_inv = false, .ws_inv = false },
        },
    };
    ESP_GOTO_ON_ERROR(i2s_channel_init_std_mode(s_ao.tx, &std_cfg), fail, TAG, "i2s std init");
    const i2s_event_callbacks_t cbs = { .on_sent = on_sent };
    ESP_GOTO_ON_ERROR(i2s_channel_register_event_callback(s_ao.tx, &cbs, NULL), fail, TAG, "i2s callbacks");

    BaseType_t ok = xTaskCreatePinnedToCore(aux_task, "audio_aux", AUX_TASK_STACK, NULL, AUX_TASK_PRIO,
                                            &s_ao.aux, tskNO_AFFINITY);
    ESP_GOTO_ON_FALSE(ok == pdPASS, ESP_ERR_NO_MEM, fail, TAG, "aux task");

    s_ao.volume = UINT16_MAX;
    s_ao.initialised = true;
    ESP_LOGI(TAG, "init: %u Hz, 16 bit stereo, ring %u bytes (%s), DMA %u x %u frames, "
             "BCK=%d WS=%d DOUT=%d XSMT=%d",
             (unsigned)s_ao.cfg.sample_rate_hz, (unsigned)ring,
             esp_ptr_external_ram(s_ao.ring_storage) ? "PSRAM" : "internal",
             (unsigned)I2S_DMA_DESC_NUM, (unsigned)I2S_DMA_FRAME_NUM,
             BOARD_I2S_BCK_GPIO, BOARD_I2S_WS_GPIO, BOARD_I2S_DOUT_GPIO, BOARD_DAC_XSMT_GPIO);
    return ESP_OK;

fail:
    if (s_ao.tx) {
        i2s_del_channel(s_ao.tx);
        s_ao.tx = NULL;
    }
    if (s_ao.space_sem) {
        vSemaphoreDelete(s_ao.space_sem);
        s_ao.space_sem = NULL;
    }
    if (s_ao.state_lock) {
        vSemaphoreDelete(s_ao.state_lock);
        s_ao.state_lock = NULL;
    }
    if (s_ao.send_lock) {
        vSemaphoreDelete(s_ao.send_lock);
        s_ao.send_lock = NULL;
    }
    heap_caps_free(s_ao.ring_storage);
    heap_caps_free(s_ao.tone_storage);
    heap_caps_free(s_ao.tone_scratch);
    s_ao.ring_storage = NULL;
    s_ao.tone_storage = NULL;
    s_ao.tone_scratch = NULL;
    return ret;
}

esp_err_t audio_out_start(void)
{
    ESP_RETURN_ON_FALSE(s_ao.initialised, ESP_ERR_INVALID_STATE, TAG, "not initialised");
    esp_err_t ret = ESP_OK;

    xSemaphoreTake(s_ao.state_lock, portMAX_DELAY);
    if (!s_ao.running) {
        portENTER_CRITICAL(&s_ao.eng_mux);
        s_ao.next_fill = NULL;          /* the DMA restarts at its first descriptor */
        s_ao.rewrite_req = false;
        s_ao.last_isr_us = 0;
        portEXIT_CRITICAL(&s_ao.eng_mux);
        ret = i2s_channel_enable(s_ao.tx);          /* clocks start, zeros are sent */
        if (ret == ESP_OK) {
            s_ao.running = true;
            vTaskDelay(pdMS_TO_TICKS(UNMUTE_DELAY_MS));   /* let the DAC PLL lock */
            xsmt_set(true);
            ESP_LOGI(TAG, "started");
        } else {
            ESP_LOGE(TAG, "i2s_channel_enable: %s", esp_err_to_name(ret));
        }
    }
    xSemaphoreGive(s_ao.state_lock);
    return ret;
}

esp_err_t audio_out_stop(void)
{
    ESP_RETURN_ON_FALSE(s_ao.initialised, ESP_ERR_INVALID_STATE, TAG, "not initialised");
    esp_err_t ret = ESP_OK;

    xSemaphoreTake(s_ao.state_lock, portMAX_DELAY);
    if (s_ao.running) {
        xsmt_set(false);
        vTaskDelay(pdMS_TO_TICKS(MUTE_RAMP_MS));     /* soft-mute ramp of the DAC */
        s_ao.running = false;
        ret = i2s_channel_disable(s_ao.tx);
        xSemaphoreTake(s_ao.send_lock, portMAX_DELAY);
        portENTER_CRITICAL(&s_ao.eng_mux);
        pcm_engine_flush(&s_ao.eng);                 /* buffered audio is discarded */
        pcm_engine_reset_output(&s_ao.eng);
        pcm_ring_drop(&s_ao.tone_ring);
        clear_dma_ring_locked();                     /* no stale audio on the next start */
        s_ao.next_fill = NULL;
        s_ao.rewrite_req = false;
        s_ao.last_isr_us = 0;
        portEXIT_CRITICAL(&s_ao.eng_mux);
        s_ao.flush_gen++;
        xSemaphoreGive(s_ao.send_lock);
        xSemaphoreGive(s_ao.space_sem);
        xTaskNotifyGive(s_ao.aux);                   /* ends a test tone */
        ESP_LOGI(TAG, "stopped");
    }
    xSemaphoreGive(s_ao.state_lock);
    return ret;
}

size_t audio_out_write(const void *pcm, size_t bytes, TickType_t timeout)
{
    if (!s_ao.initialised || pcm == NULL) {
        return 0;
    }
    bytes &= ~(size_t)(AUDIO_OUT_BYTES_PER_FRAME - 1);
    if (bytes == 0) {
        return 0;
    }

    TimeOut_t   to;
    TickType_t  remaining = timeout;
    vTaskSetTimeOutState(&to);

    const uint32_t gen = s_ao.flush_gen;
    for (;;) {
        /* A flush while we waited for space: this data belongs to before the
         * flush (seek, skip) and must not be played after it. */
        if (s_ao.flush_gen != gen) {
            return 0;
        }
        /* Single writer: the free space can only grow behind our back. */
        size_t space = pcm_ring_free(&s_ao.ring) & ~(size_t)(AUDIO_OUT_BYTES_PER_FRAME - 1);
        size_t n = bytes < space ? bytes : space;
        if (n > 0) {
            xSemaphoreTake(s_ao.send_lock, portMAX_DELAY);
            if (s_ao.flush_gen != gen) {
                xSemaphoreGive(s_ao.send_lock);
                return 0;
            }
            size_t sent = pcm_ring_write(&s_ao.ring, pcm, n);
            xSemaphoreGive(s_ao.send_lock);
            portENTER_CRITICAL(&s_ao.stat_mux);
            s_ao.frames_written += sent / AUDIO_OUT_BYTES_PER_FRAME;
            portEXIT_CRITICAL(&s_ao.stat_mux);
            return sent;
        }
        if (xTaskCheckForTimeOut(&to, &remaining) == pdTRUE) {
            return 0;
        }
        xSemaphoreTake(s_ao.space_sem, remaining);
    }
}

esp_err_t audio_out_set_mute(bool mute)
{
    ESP_RETURN_ON_FALSE(s_ao.initialised, ESP_ERR_INVALID_STATE, TAG, "not initialised");
    xSemaphoreTake(s_ao.state_lock, portMAX_DELAY);
    /* Never un-mute while the clocks are stopped: the DAC would see garbage. */
    xsmt_set(!mute && s_ao.running);
    xSemaphoreGive(s_ao.state_lock);
    return ESP_OK;
}

/* Spotify's volume (0..65535, linear slider) -> gain. A logarithmic curve
 * over 50 dB like librespot's default, so that the slider feels even; 100 %
 * is unity gain, i.e. the music passes bit-exact. */
#define VOLUME_RANGE_DB 50.0f

void audio_out_set_volume(uint16_t volume)
{
    if (!s_ao.initialised) {
        return;
    }
    uint32_t gain;
    if (volume == 0) {
        gain = 0;
    } else if (volume == UINT16_MAX) {
        gain = PCM_ENGINE_GAIN_UNITY;
    } else {
        float db = ((float)volume / 65535.0f - 1.0f) * VOLUME_RANGE_DB;
        gain = (uint32_t)(powf(10.0f, db / 20.0f) * (float)PCM_ENGINE_GAIN_UNITY + 0.5f);
    }
    portENTER_CRITICAL(&s_ao.eng_mux);
    s_ao.eng.gain_target = gain;
    portEXIT_CRITICAL(&s_ao.eng_mux);
    s_ao.volume = volume;
}

uint16_t audio_out_get_volume(void)
{
    return s_ao.initialised ? s_ao.volume : UINT16_MAX;
}

void audio_out_set_paused(bool paused)
{
    if (!s_ao.initialised) {
        return;
    }
    portENTER_CRITICAL(&s_ao.eng_mux);
    s_ao.eng.paused = paused;
    portEXIT_CRITICAL(&s_ao.eng_mux);
}

void audio_out_flush(void)
{
    if (!s_ao.initialised) {
        return;
    }
    s_ao.flush_gen++;
    /* The producer is either outside audio_out_write() or blocked waiting for
     * space; in both cases it does not hold send_lock for long. */
    xSemaphoreTake(s_ao.send_lock, portMAX_DELAY);
    portENTER_CRITICAL(&s_ao.eng_mux);
    pcm_engine_flush(&s_ao.eng);
    /* A tone keeps playing undisturbed; otherwise cut the queued DMA audio. */
    s_ao.rewrite_req = s_ao.running && !s_ao.eng.tone_mode;
    portEXIT_CRITICAL(&s_ao.eng_mux);
    xSemaphoreGive(s_ao.send_lock);
    xSemaphoreGive(s_ao.space_sem);     /* wake a waiting writer: it sees the new generation */
}

void audio_out_get_stats(audio_out_stats_t *out)
{
    if (out == NULL) {
        return;
    }
    memset(out, 0, sizeof(*out));
    if (!s_ao.initialised) {
        return;
    }
    portENTER_CRITICAL(&s_ao.stat_mux);
    out->frames_written = s_ao.frames_written;
    portEXIT_CRITICAL(&s_ao.stat_mux);
    portENTER_CRITICAL(&s_ao.eng_mux);
    out->frames_played = s_ao.eng.frames_played;
    out->frames_dropped = s_ao.eng.frames_dropped;
    out->underruns = s_ao.eng.underruns;
    out->paused = s_ao.eng.paused;
    portEXIT_CRITICAL(&s_ao.eng_mux);
    out->buffered_bytes = (uint32_t)pcm_ring_used(&s_ao.ring);
    out->running = s_ao.running;
    out->muted = s_ao.muted;
    out->dma_underruns = s_ao.dma_underruns;
    out->dma_late = s_ao.dma_late;
}

esp_err_t audio_out_tone_start(float freq_hz, float dbfs, uint32_t duration_ms)
{
    ESP_RETURN_ON_FALSE(s_ao.initialised && s_ao.running, ESP_ERR_INVALID_STATE, TAG, "not running");
    tone_gen_t t;
    if (!tone_gen_init(&t, s_ao.cfg.sample_rate_hz, freq_hz, dbfs, duration_ms)) {
        return ESP_ERR_INVALID_ARG;
    }
    portENTER_CRITICAL(&s_ao.tone_mux);
    s_ao.tone_next = t;
    s_ao.tone_start_req = true;
    s_ao.tone_stop_req = false;
    s_ao.tone_active = true;
    portEXIT_CRITICAL(&s_ao.tone_mux);
    xTaskNotifyGive(s_ao.aux);
    return ESP_OK;
}

void audio_out_tone_stop(void)
{
    if (!s_ao.initialised) {
        return;
    }
    portENTER_CRITICAL(&s_ao.tone_mux);
    if (s_ao.tone_start_req) {
        /* not picked up by the aux task yet: cancel it */
        s_ao.tone_start_req = false;
        if (!s_ao.tone_running) {
            s_ao.tone_active = false;
        }
    }
    s_ao.tone_stop_req = true;
    portEXIT_CRITICAL(&s_ao.tone_mux);
    xTaskNotifyGive(s_ao.aux);
}

bool audio_out_tone_active(void)
{
    return s_ao.tone_active;
}
