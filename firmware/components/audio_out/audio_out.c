/*
 * audio_out - I2S sink for the PCM5102A (see include/audio_out.h).
 *
 * Design notes
 * ------------
 * - Driver: i2s_std (the "new" I2S driver). The ESP32-S3 has no APLL, so the
 *   legacy-driver/APLL sink shipped with bell cannot be used.
 * - The PCM5102A runs without MCLK (SCK tied to GND): it regenerates its
 *   system clock from BCK, which therefore has to be continuous. We never stop
 *   the I2S channel while "running"; silence is sent as zeros.
 * - The DMA buffers are refilled directly in the I2S "buffer sent" interrupt
 *   (on_sent), not by a task. Bench tests showed a high-priority feeder task on
 *   core 1 being held up for ~100 ms now and then (track changes in
 *   particular), longer than the DMA can bridge: audible gaps although the
 *   ring buffer was full. The interrupt only copies 2 kB per 11.6 ms from the
 *   ring buffer, so it is cheap, and it does not depend on any task.
 * - Missed interrupts are caught up: the DMA descriptors form a ring; we keep
 *   track of the next descriptor to refill and, when one interrupt reports
 *   several finished buffers at once, refill all of them in order. Only an
 *   interrupt more than ~7 buffers (81 ms) late still causes a gap.
 * - Ring buffer: pcm_ring, lock-free single producer (audio_out_write) /
 *   single consumer (the interrupt), storage in PSRAM. Flush, tone hand-over
 *   and stop exclude the interrupt with one spinlock (eng_mux).
 * - What goes into each buffer (music, tone, fades, silence) is decided by
 *   pcm_engine, plain C that is unit-tested on the host.
 * - Seek/skip: the ~70 ms already queued in the DMA ring are rewritten with a
 *   short ramp to silence, so the new position starts quickly and click-free.
 * - Test tone: generated by a low-priority helper task (floating point is not
 *   allowed in interrupts) into its own small ring; the music ring is left
 *   alone meanwhile (the producer sees back-pressure as if paused).
 */
